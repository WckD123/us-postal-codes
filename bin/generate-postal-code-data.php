<?php

/**
 * Builds data/us/{first 3 digits}.php from the GeoNames downloads.
 * Run from a clone of this repo: php bin/generate-postal-code-data.php <input> [<output>]
 *
 * Getting the input into <input>:
 *   for c in US PR VI GU AS MP; do curl -sSLO https://download.geonames.org/export/zip/$c.zip && unzip -o -q $c.zip -d $c; done
 */

use WckD123\UsPostalCodes\UsAddressState;
use WckD123\UsPostalCodes\PostalCodeLookup;

require __DIR__ . '/../vendor/autoload.php';

const US_FOLDERS          = ['US', 'PR', 'VI', 'GU', 'AS', 'MP'];
const FILE_HEADER_COMMENT = 'Generated by bin/generate-postal-code-data.php - do not edit by hand. Sources and licences: ../NOTICE.md';

main($argv);

function main(array $argv): void
{
    if (isset($argv[1]) === false)
    {
        fail('Usage: php bin/generate-postal-code-data.php <input folder> [<output folder>]');
    }

    $input  = rtrim($argv[1], '/');
    $output = rtrim($argv[2] ?? dirname(__DIR__) . '/data', '/');

    [$entries, $skipped] = readUsRows($input);

    writeFiles($output . '/us', $entries);

    echo count($entries) . ' codes written, ' . $skipped . " rows skipped\n";
}

function readUsRows(string $input): array
{
    $entries = [];
    $skipped = 0;

    foreach (US_FOLDERS as $code)
    {
        $path = $input . '/' . $code . '/' . $code . '.txt';

        if (is_file($path) === false)
        {
            fail('Missing source file ' . $path);
        }

        $handle = fopen($path, 'r');

        while (($row = fgetcsv($handle, null, "\t", '"', '')) !== false)
        {
            $state = $code === 'US' ? ($row[4] ?? '') : $code;
            $zip   = $row[1] ?? '';
            $city  = trim($row[2] ?? '');

            // The first row for a ZIP wins; the repeats are FPO rows next to a real ZIP.
            if ((preg_match('/^\d{5}$/', $zip) !== 1) ||
                (isset(UsAddressState::NAMES_BY_CODE[$state]) === false) ||
                ($city === '') ||
                (isset($entries[$zip]) === true))
            {
                $skipped++;

                continue;
            }

            $entries[$zip] = [PostalCodeLookup::STATE => $state, PostalCodeLookup::CITIES => [$city]];
        }

        fclose($handle);
    }

    return [$entries, $skipped];
}

function writeFiles(string $folder, array $entries): void
{
    if (is_dir($folder) === false)
    {
        mkdir($folder, 0755, true);
    }

    foreach (glob($folder . '/*.php') as $oldFile)
    {
        unlink($oldFile);
    }

    ksort($entries, SORT_STRING);

    $byPrefix = [];

    foreach ($entries as $code => $entry)
    {
        $byPrefix[substr((string) $code, 0, 3)][(string) $code] = $entry;
    }

    foreach ($byPrefix as $prefix => $prefixEntries)
    {
        file_put_contents($folder . '/' . $prefix . '.php', renderFile($prefixEntries));
    }
}

function renderFile(array $entries): string
{
    $lines = ["<?php", "", '// ' . FILE_HEADER_COMMENT, "", "return ["];

    foreach ($entries as $code => $entry)
    {
        $cities = implode(', ', array_map(fn ($city) => var_export($city, true), $entry[PostalCodeLookup::CITIES]));

        $lines[] = '    ' . var_export((string) $code, true) . ' => ['
            . var_export(PostalCodeLookup::STATE, true) . ' => ' . var_export($entry[PostalCodeLookup::STATE], true) . ', '
            . var_export(PostalCodeLookup::CITIES, true) . ' => [' . $cities . ']],';
    }

    $lines[] = "];";

    return implode("\n", $lines) . "\n";
}

function fail(string $message): never
{
    fwrite(STDERR, $message . "\n");

    exit(1);
}
